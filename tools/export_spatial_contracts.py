"""Generate frontend types and JSON Schema from the Python spatial contracts."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root))
from earthglass.spatial.models import Observation, Viewport, ProviderHealth

definitions = {}
for model in (Observation, Viewport, ProviderHealth):
    schema = model.model_json_schema()
    definitions.update(schema.pop("$defs", {}))
    definitions[model.__name__] = schema


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        return "(" + ts_type(schema.get("items", {})) + ")[]"
    if kind == "object":
        if "properties" not in schema:
            return "Record<string, unknown>"
        required = schema.get("required", [])
        return "{ " + " ".join(f"{json.dumps(key)}{'' if key in required else '?'}: {ts_type(value)};" for key, value in schema["properties"].items()) + " }"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


schema_path = root / "earthglass/spatial/spatial-v1.schema.json"
types_path = root / "obeos-earth/src/contracts.ts"
schema_text = json.dumps({"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": definitions, "$ref": "#/$defs/Observation"}, indent=2) + "\n"
types_text = "// Generated by tools/export_spatial_contracts.py. Do not edit by hand.\n" + "\n".join(
    "export type " + name + " = " + ts_type(schema) + ";" for name, schema in sorted(definitions.items())) + "\n"
if "--check" in sys.argv:
    assert schema_path.read_text(encoding="utf8") == schema_text, "Spatial JSON Schema is stale"
    assert types_path.read_text(encoding="utf8") == types_text, "Spatial TypeScript types are stale"
else:
    schema_path.write_text(schema_text, encoding="utf8")
    types_path.write_text(types_text, encoding="utf8")
